def test_native_lock_and_vendored_checksum_bytes_have_stable_checkout_policy() -> None:
    attributes = (ROOT / ".gitattributes").read_text(encoding="utf-8").splitlines()
    lock_rule = "src/humanbrain/_native_src/Cargo.lock text eol=lf"
    vendor_rule = "src/humanbrain/_native_src/vendor/** -text -whitespace"

    assert ".gitattributes text eol=lf" in attributes
    assert lock_rule in attributes
    assert vendor_rule in attributes
    assert attributes.index(vendor_rule) > attributes.index("*.rs text eol=lf")
    assert attributes.index(vendor_rule) > attributes.index("*.json text eol=lf")


def test_every_vendored_cargo_file_matches_its_frozen_checksum() -> None:
    vendor_root = ROOT / "src" / "humanbrain" / "_native_src" / "vendor"
    checksum_paths = sorted(vendor_root.glob("*/.cargo-checksum.json"))

    assert len(checksum_paths) == 6
    for checksum_path in checksum_paths:
        crate_root = checksum_path.parent
        record = json.loads(checksum_path.read_text(encoding="utf-8"))
        expected = record["files"]
        actual_paths = {
            path.relative_to(crate_root).as_posix()
            for path in crate_root.rglob("*")
            if path.is_file() and path != checksum_path
        }

        assert actual_paths == set(expected)
        for relative_path, expected_digest in expected.items():
            payload = (crate_root / relative_path).read_bytes()
            assert hashlib.sha256(payload).hexdigest() == expected_digest


def test_native_source_digest_covers_every_recursive_cargo_input(tmp_path: Path) -> None:
    source_root = tmp_path / "native-source"
    _write_build_tree(source_root)

    manifest = native._native_build_input_manifest(source_root)
    first_digest = native._source_digest(source_root)

    assert tuple(name for name, _payload in manifest) == (
        ".cargo/config.toml",
        "Cargo.lock",
        "Cargo.toml",
        "build.rs",
        "src/lib.rs",
        "src/nested/procedural.rs",
        "vendor/identity-dependency/.cargo-checksum.json",
        "vendor/identity-dependency/src/lib.rs",
    )
    assert len(first_digest) == 64

    (source_root / "src" / "nested" / "procedural.rs").write_bytes(
        b"pub fn frontier() -> u64 { 2 }\n"
    )
    second_digest = native._source_digest(source_root)

    assert second_digest != first_digest
    assert (tmp_path / first_digest) != (tmp_path / second_digest)
    assert native.NativeLibraryIdentity(
        source_digest=second_digest,
        binary_size=1,
        binary_sha256="0" * 64,
    ).source_digest == second_digest


