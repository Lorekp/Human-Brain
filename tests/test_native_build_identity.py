ROOT = Path(__file__).parents[1]


def _write_build_tree(root: Path) -> None:
    (root / "src" / "nested").mkdir(parents=True)
    (root / ".cargo").mkdir()
    (root / "vendor" / "identity-dependency" / "src").mkdir(parents=True)
    (root / "target" / "release").mkdir(parents=True)
    (root / "Cargo.toml").write_bytes(
        b"[package]\nname='identity-test'\nversion='0.1.0'\nedition='2021'\n"
    )
    (root / "Cargo.lock").write_bytes(
        b"# This file is automatically @generated by Cargo.\nversion = 4\n\n"
        b"[[package]]\nname = \"identity-test\"\nversion = \"0.1.0\"\n"
    )
    (root / ".cargo" / "config.toml").write_bytes(native._VENDORED_CARGO_CONFIG)
    (root / "build.rs").write_bytes(b"fn main() {}\n")
    (root / "src" / "lib.rs").write_bytes(b"mod nested;\n")
    (root / "src" / "nested" / "procedural.rs").write_bytes(
        b"pub fn frontier() -> u64 { 1 }\n"
    )
    (root / "vendor" / "identity-dependency" / ".cargo-checksum.json").write_bytes(
        b'{"files":{},"package":"synthetic"}'
    )
    (root / "vendor" / "identity-dependency" / "src" / "lib.rs").write_bytes(
        b"pub fn dependency() -> u64 { 1 }\n"
    )
    (root / "target" / "release" / "cached.rs").write_bytes(b"not a build input\n")


