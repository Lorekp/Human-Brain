"""Observation and discarded local-update copies for one localization protocol.

No replacement reader, monkeypatch, optimizer or answer-selected forward inputs.
The runner owns checkpoint custody, fixed conditions, accounting and deadlines.
"""
import copy

import torch
from torch.nn import functional as F

from humanbrain.byte_sequence_decoder import BYTE_BOS, BYTE_EOS
from humanbrain.plastic_memory import LocalMemoryState, PlasticMemoryState


def clone(value):
    """Own receipt tensors independently of subsequent local state updates."""
    if isinstance(value, torch.Tensor):
        return value.detach().clone()
    if isinstance(value, dict):
        return {key: clone(item) for key, item in value.items()}
    if isinstance(value, list):
        return [clone(item) for item in value]
    return copy.deepcopy(value)


@torch.no_grad()
def traced_ingest(model, documents):
    """Same per-document EOS, continuous writer carry, and single final purge.

    Token-sized calls reuse the production write arithmetic. They incur extra
    public validation/copies, but do not change byte exposure or the local rule.
    Map observations repeat only the maps on the actual returned writer activity.
    """
    if not documents or any(not isinstance(d, bytes) for d in documents):
        raise ValueError("documents must be a nonempty sequence of raw bytes")
    memory = model.memory
    state = memory.initial_local_state(
        1, credit_mode="aggregate" if model.mode == "aggregate" else "tagged"
    )
    model._check_state_mode(state)
    frozen_writer = model.mode in {"frozen", "writer_maps_frozen"}
    forward = PlasticMemoryState(state.synapses, state.cell.activity)
    rows = []
    for document_index, document in enumerate(documents):
        codes = model._encoded(document)
        for byte_index, token in enumerate((*document, BYTE_EOS)):
            values = codes[:, byte_index:byte_index + 1]
            mask = torch.ones((1, 1), dtype=torch.bool, device=values.device)
            previous_writer = forward.writer if frozen_writer else state.cell.activity
            if frozen_writer:
                forward = memory.write(values, mask, forward)
                writer, matrix = forward.writer, forward.synapses
            else:
                state = memory.write_local(
                    values, mask, state, writes_enabled=model.mode != "writes_disabled"
                )
                writer, matrix = state.cell.activity, state.synapses
            drive = F.linear(writer, memory.key_weight, memory.key_bias)
            key, gain = memory._normalized_local_map(drive)
            if frozen_writer:
                key = F.normalize(drive, dim=-1, eps=1e-8)
            value = torch.tanh(F.linear(writer, memory.value_weight, memory.value_bias))
            strength = torch.sigmoid(F.linear(writer, memory.strength_weight, memory.strength_bias))
            rows.append(clone({
                "document_index": document_index, "byte_index": byte_index, "token": token,
                "writer_before": previous_writer, "writer": writer,
                "key": key, "value": value, "strength": strength,
                "beta": torch.zeros_like(strength) if model.mode == "writes_disabled" else strength,
                "key_norm": drive.norm(dim=-1, keepdim=True), "key_gain": gain,
                "value_gain": 1 - value.square(), "strength_gain": strength * (1 - strength),
                "synapses": matrix,
            }))
    if frozen_writer:
        state = LocalMemoryState(
            forward.synapses.clone(), memory.controller.initial_learning_state(1),
            {key: torch.zeros_like(value) for key, value in state.credit.items()},
            state.credit_mode,
        )
        memory._check_local_state(state)
    else:
        state = memory.purge_local_writer(state)
    return state, rows


@torch.no_grad()
def observed_query(model, query, state):
    """One production context traversal; observe every phase, label supplements.

    Only the ordinary prefix through learned EOS/cap contributes generated bytes.
    Later clock observations are diagnostic evaluations and never emitted bytes.
    """
    context = model._prediction_context(query, state)
    activity = context[:, :model.query_size]
    key = F.normalize(
        F.linear(activity, model.memory.query_weight, model.memory.query_bias), dim=-1, eps=1e-8
    )
    features, scores = [], []
    decoder_state, previous = None, BYTE_BOS
    output, stop_reason, decisions = bytearray(), None, 0
    for position in range(3):
        step = model.decoder.local_step(
            context, torch.tensor([previous], dtype=torch.int64, device="cpu"), decoder_state
        )
        decoder_state = step.state
        previous = int(step.scores.argmax(-1)[0])
        features.append(step.features[0].clone())
        scores.append(step.scores[0].clone())
        if stop_reason is None:
            decisions += 1
            if previous == BYTE_EOS:
                stop_reason = "eos"
            elif position == 2:
                stop_reason = "limit"
            else:
                output.append(previous)
    return clone({
        "context": context, "query_activity": activity, "query_key": key,
        "read": context[:, model.query_size:],
        "phase_features": torch.stack(features), "phase_scores": torch.stack(scores),
        "generated_hex": bytes(output).hex(), "stop_reason": stop_reason, "decisions": decisions,
        "extra_phase_evaluations": 3 - decisions, "phase_evaluations": 3,
        "query_traversals": 1, "query_key_observation_recomputations": 1,
    })


def parameter_block(name):
    if name.startswith("query_cell.") or name.startswith("memory.query_"):
        return "address"
    if name.startswith("memory."):
        return "writer"
    raise ValueError(f"unexpected trainable parameter: {name}")


@torch.no_grad()
def propose_blocks(model, query, target, state, observation):
    """One real teacher call on a discarded copy; no fitted trajectory.

    The runner supplies the original-order baseline observation from the same
    frozen checkpoint/documents/query. Phase-local synapses cannot be changed by
    another phase's correction. Thus its saved scores and original weights give
    each actual pre-update signal without another teacher call or interception.
    Their mean must equal the production receipt, including the upstream cast.
    """
    if not isinstance(target, bytes) or len(target) != 2:
        raise ValueError("proposal teacher must contain two bytes")
    if model.mode != "tagged":
        raise ValueError("proposal conditions are fixed to the tagged checkpoint")
    worker = copy.deepcopy(model)
    owned_state = worker.memory.restore_local_state(state.snapshot())
    before = {name: p.detach().clone() for name, p in worker.named_parameters()}
    old_output = worker.decoder.output_weights.clone()
    scores = observation["phase_scores"].clone()
    if scores.shape != (3, 257) or scores.dtype != torch.float64:
        raise ValueError("proposal requires saved three-phase double potentials")
    residuals = -scores
    for phase, token in enumerate((*target, BYTE_EOS)):
        residuals[phase, token] += 1
    weights = old_output[:, 3:].reshape(257, 3, 96)
    signals = []
    for phase in range(3):
        active_weights = (
            weights * observation["phase_features"][phase, :3][None, :, None]
        ).sum(1)
        signals.append(F.linear(-residuals[phase:phase + 1], active_weights.T)[0])
    signals = torch.stack(signals)
    mean = torch.zeros((1, 96), dtype=torch.float64)
    for signal in signals:
        mean.add_(signal[None])
    mean = (mean / 3).to(dtype=observation["context"].dtype)
    feedback = worker.teach(query, target, owned_state, 0.01)
    if not torch.equal(mean, feedback.mean_context_signal):
        raise AssertionError("saved baseline signals differ from actual teacher mean")
    blocks = {"writer": {}, "address": {}}
    for name, parameter in worker.named_parameters():
        blocks[parameter_block(name)][name] = {
            "before": before[name], "after": parameter.clone(),
            "delta": parameter - before[name],
        }
    output_delta = worker.decoder.output_weights - old_output
    worker.decoder.output_weights.copy_(old_output)
    return clone({
        "blocks": blocks, "teacher_targets": [*target, BYTE_EOS],
        "teacher_scores": scores, "teacher_residuals": residuals,
        "teacher_context_signals": signals,
        "signal_scope": (
            "derived from saved ordinary baseline scores and independent pre-update "
            "phase synapses; exact actual mean checked"
        ),
        "actual_mean_context_signal": feedback.mean_context_signal,
        "teacher_count": feedback.teacher_count, "mean_loss": feedback.mean_loss,
        "decoder_changed_steps": feedback.decoder_changed_steps,
        "query_updated": feedback.query_updated, "memory_updated": feedback.memory_updated,
        "discarded_output_delta": output_delta, "output_restored": True,
        "teacher_query_traversals": 1,
    })


@torch.no_grad()
def perturbed_model(model, proposal, block, sign):
    """An isolated endpoint +/- actual local displacement, fixed old output.

    Positive uses the actual recorded after value, avoiding cancellation in
    before+(after-before). Negative is before-(after-before), with each operation
    in the parameter dtype. This asymmetric rounding is a finite update-effect
    comparison, not a precise derivative. No normalization or line search occurs.
    """
    if block not in {"writer", "address"} or type(sign) is not int or sign not in {-1, 1}:
        raise ValueError("use exactly writer/address and integer sign -1/+1")
    worker = copy.deepcopy(model)
    parameters = dict(worker.named_parameters())
    for name, change in proposal["blocks"][block].items():
        if parameter_block(name) != block or not torch.equal(parameters[name], change["before"]):
            raise ValueError("proposal and frozen endpoint do not match")
        candidate = change["after"] if sign == 1 else parameters[name] - change["delta"]
        if not bool(torch.isfinite(candidate).all()):
            raise ValueError("nonfinite perturbed parameter")
        parameters[name].copy_(candidate)
    return worker
