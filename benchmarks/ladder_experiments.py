@dataclass(frozen=True)
class Codebook:
    """One arm's mapping from token ids to injected cell assemblies.

    ``assemblies`` is ``(token_count, k)`` int32 with sorted distinct reservoir
    cells per row, or ``None`` for the explicit arm (built-in wiring kept).
    """

    mode: str
    n_e: int
    k: int
    seed: int | None
    assemblies: np.ndarray | None
    sha256: str


def _codebook_token_name(token_id: int) -> str:
    """Canonical Layer-1 name of a token id (byte characters + primitives)."""
    token_id = int(token_id)
    if 0 <= token_id < 256:
        return chr(token_id)
    spec = typed_program._ID_TO_SPEC.get(token_id)
    if spec is None:
        raise ValueError(f"token id {token_id} outside the Layer-1 vocabulary")
    return spec.token


def _similarity_assembly_cells(name: str, n_e: int, k: int) -> tuple[int, ...]:
    """Frozen v1 similarity projection of one token name onto k cells.

    Exact pinned definition (changing it requires re-pinning
    ``tests/test_ladder_codebook.py``; stdlib only, no external dependencies):

    1. ``text = name.lower()`` and pad it: ``padded = f"  {text}  "``.
    2. Features are every contiguous character trigram of ``padded``.
    3. A counting vector ``v`` in R^n_e starts at zero. Each feature string
       ``g`` contributes one unit vote to the cell
       ``h % n_e``, where ``h`` is the big-endian uint64 value of
       ``blake2b(g.encode("utf-8"), digest_size=8)``: ``v[cell] += 1``.
       Votes are deliberately UNSIGNED so that every shared-trigram cell is
       positive evidence; with one vote per feature a signed scheme would
       push half of them below all zero cells and destroy family structure.
    4. Rank all cells ascending by key ``(-v[c], tiebreak)`` where
       ``tiebreak = blake2b(f"{name}\\x00{c}".encode("utf-8"), digest_size=8)``
       as a big-endian uint64. Evidence strength dominates, then a
       deterministic per-(name, cell) pseudorandom priority spreads
       zero-evidence filler cells like a random baseline instead of
       collapsing them onto low indices.
    5. The assembly is the sorted first ``k`` ranked cells.

    The projection is run-seed independent by construction, and overlap
    between two tokens' assemblies is monotone in shared character structure.
    """
    vector = np.zeros(n_e, dtype=np.int64)
    padded = f"  {name.lower()}  "
    for index in range(len(padded) - 2):
        feature = padded[index : index + 3]
        digest = int.from_bytes(
            blake2b(feature.encode("utf-8"), digest_size=8).digest(), "big"
        )
        vector[digest % n_e] += 1
    ranked = sorted(
        range(n_e),
        key=lambda cell: (
            -int(vector[cell]),
            int.from_bytes(
                blake2b(
                    f"{name}\x00{cell}".encode("utf-8"), digest_size=8
                ).digest(),
                "big",
            ),
        ),
    )
    return tuple(sorted(ranked[:k]))


def build_codebook(
    mode: str,
    *,
    token_count: int,
    n_e: int,
    k: int,
    seed: int,
) -> Codebook:
    """Materialize one codebook arm over the full Layer-1 vocabulary."""
    if mode not in CODEBOOKS:
        raise ValueError(f"unknown codebook mode {mode!r}; expected one of {CODEBOOKS}")
    if not 1 <= k <= n_e:
        raise ValueError(f"assembly size k={k} must be within [1, n_e={n_e}]")
    if token_count < 2:
        raise ValueError("token_count must cover at least two tokens")

    assemblies: np.ndarray | None = None
    if mode == "random":
        # Distributed control arm: per-token domain-separated streams make the
        # mapping order-independent and reproducible under the seed alone.
        rows = np.empty((token_count, k), dtype=np.int32)
        for token_id in range(token_count):
            rng = np.random.default_rng([seed, _CODEBOOK_RNG_SALT, token_id])
            rows[token_id] = np.sort(rng.choice(n_e, size=k, replace=False))
        assemblies = rows
    elif mode == "similarity":
        names = [_codebook_token_name(token_id) for token_id in range(token_count)]
        flat = np.fromiter(
            (
                cell
                for name in names
                for cell in _similarity_assembly_cells(name, n_e, k)
            ),
            dtype=np.int32,
            count=token_count * k,
        )
        assemblies = flat.reshape(token_count, k)

    record = {
        "mode": mode,
        "n_e": int(n_e),
        "k": int(k),
        # Only the random arm consumes the seed; explicit and similarity are
        # seed-independent, so their provenance digests must not vary by seed.
        "seed": int(seed) if mode == "random" else None,
        "assemblies": None if assemblies is None else assemblies.astype(int).tolist(),
    }
    return Codebook(
        mode=mode,
        n_e=n_e,
        k=k,
        seed=int(seed) if mode == "random" else None,
        assemblies=assemblies,
        sha256=sha256(_canonical_json(record)).hexdigest(),
    )


def install_codebook(circuit: RecurrentCellCircuit, codebook: Codebook) -> None:
    """Overwrite the circuit's afferent table with the codebook assemblies.

    Both grow and completion inject tokens through this single table, so one
    install gives same-token-same-assembly across both phases.
    """
    if codebook.mode == "explicit":
        raise ValueError("the explicit arm keeps the built-in afferent wiring")
    if codebook.assemblies is None:
        raise ValueError("non-explicit codebook is missing its assembly table")
    if codebook.n_e > circuit.active_reservoir_cells:
        raise ValueError("codebook E-population exceeds the active reservoir")
    targets = circuit._afferent_targets
    if codebook.assemblies.shape != targets.shape:
        raise ValueError(
            f"assembly table shape {codebook.assemblies.shape} does not match "
            f"the circuit afferent table {targets.shape}"
        )
    if not np.all(np.diff(codebook.assemblies.astype(np.int64), axis=1) > 0):
        raise ValueError("every assembly must be k distinct cells in sorted order")
    if int(codebook.assemblies.max()) >= circuit.active_reservoir_cells:
        raise ValueError("assembly cell outside the active reservoir population")
    np.copyto(targets, codebook.assemblies)
    circuit.synchronize_structure_from_host()


def recurrent_sign_metrics(circuit: RecurrentCellCircuit) -> dict[str, object]:
    """Canonical sign-structure metrics of the circuit's recurrent weights.

    ``_recurrent_weights_pa`` is ``signs * recurrent_current_pa`` repeated
    across the fan-out columns (recurrent.py signs :261-266, applied :268),
    so column 0 carries the whole sign pattern. The hash pins ONLY the sign
    vector (int8 -1/0/+1 canonical bytes), staying stable under
    ``recurrent_current_pa`` retunes; group magnitudes are reported beside it
    as the mechanism-engagement check (both equal recurrent_current_pa).
    """
    weights = circuit._recurrent_weights_pa[:, 0]
    signs = np.sign(weights).astype(np.int8)
    excitatory = signs > 0
    inhibitory = signs < 0

    def _mean_abs(mask: np.ndarray) -> float | None:
        return float(np.mean(np.abs(weights[mask]))) if bool(mask.any()) else None

    return {
        "sign_sha256": sha256(signs.tobytes()).hexdigest(),
        "active_cells": int(circuit.active_reservoir_cells),
        "excitatory_cells": int(excitatory.sum()),
        "inhibitory_cells": int(inhibitory.sum()),
        "zero_sign_cells": int((signs == 0).sum()),
        "mean_abs_weight_excitatory_pa": _mean_abs(excitatory),
        "mean_abs_weight_inhibitory_pa": _mean_abs(inhibitory),
    }


def _canonical_json(value: object) -> bytes:
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def _fail(message: str) -> None:
    raise SystemExit(f"ladder_experiments: {message}")


def _load_frozen_curriculum_source() -> dict[str, object]:
    """Read the public frozen protocol as curriculum source data (never executed)."""
    raw = FROZEN_PROTOCOL_PATH.read_bytes()
    digest = sha256(raw).hexdigest()
    if digest != typed_composition.COMPOSITION_PROTOCOL_SHA256:
        _fail(
            "frozen protocol bytes do not match the pinned SHA-256 "
            f"({digest} != {typed_composition.COMPOSITION_PROTOCOL_SHA256})"
        )
    record = json.loads(raw.decode("utf-8"))
    return {
        "templates": record["templates"],
        "identity_prompts": record["identity_prompts"],
        "frozen_protocol_sha256": digest,
    }


def _pool_literals(seed: int) -> tuple[int, ...]:
    """Derive the seed's unique literal pool, disjoint from the spent a012 set."""
    forbidden = set(_A012_SPENT_LITERALS)
    values: list[int] = []
    counter = 0
    while len(values) < _POOL_LITERAL_COUNT:
        domain = f"humanbrain/ladder-experiments/v1/pool-literal/{seed}/{counter}"
        digest = sha256(domain.encode("utf-8")).digest()
        value = int.from_bytes(digest[:2], "big") % 199 - 99
        counter += 1
        if value in forbidden:
            continue
        forbidden.add(value)
        values.append(value)
    return tuple(values)


def _task_record(task: typed_composition.CompositionTask) -> dict[str, object]:
    return {
        "task_id": task.task_id,
        "cohort": task.cohort,
        "family_id": task.family_id,
        "template_id": task.template_id,
        "literal": task.literal,
        "opaque_ordinal": task.opaque_ordinal,
        "prompt": task.prompt,
        "signature": task.signature.to_record(),
        "teacher_tokens": list(task.teacher_tokens),
        "cases": [
            {
                "case_id": case.case_id,
                "arguments": list(case.arguments),
                "expected": case.expected,
            }
            for case in task.cases
        ],
    }


def build_curriculum(seed: int, data_scale: int) -> dict[str, object]:
    """Materialize one fresh per-seed cohort via typed_composition generators."""
    source = _load_frozen_curriculum_source()
    pool_literals = _pool_literals(seed)
    calibration_literals = pool_literals[:_CALIBRATION_LITERAL_COUNT]
    identifier_domain = f"humanbrain/ladder-experiments/v1/entry-point/seed/{seed}"
    order_domain = f"humanbrain/ladder-experiments/v1/task-order/seed/{seed}"
    record = {
        "templates": source["templates"],
        "literals": list(pool_literals),
        "identity_prompts": source["identity_prompts"],
    }
    train_pool = typed_composition._materialize_tasks(
        typed_composition._task_specs(record, cohort="TRAIN", literals=pool_literals),
        identifier_domain=identifier_domain,
        order_domain=order_domain + "/train",
        ordinal_offset=0,
    )
    if data_scale > len(train_pool):
        _fail(
            f"data_scale {data_scale} exceeds the {len(train_pool)}-task "
            "per-seed train pool"
        )
    train_tasks = train_pool[:data_scale]
    calibration_tasks = typed_composition._materialize_tasks(
        typed_composition._task_specs(
            record, cohort="CALIBRATION", literals=calibration_literals
        ),
        identifier_domain=identifier_domain,
        order_domain=order_domain + "/calibration",
        ordinal_offset=len(train_pool),
    )
    curriculum_digest = sha256(
        _canonical_json(
            {
                "seed": seed,
                "identifier_domain": identifier_domain,
                "order_domain": order_domain,
                "pool_literals": list(pool_literals),
                "calibration_literals": list(calibration_literals),
                "frozen_protocol_sha256": source["frozen_protocol_sha256"],
                "train": [_task_record(task) for task in train_tasks],
                "calibration": [_task_record(task) for task in calibration_tasks],
            }
        )
    ).hexdigest()
    return {
        "seed": seed,
        "identifier_domain": identifier_domain,
        "order_domain": order_domain,
        "pool_literals": pool_literals,
        "calibration_literals": calibration_literals,
        "frozen_protocol_sha256": source["frozen_protocol_sha256"],
        "train_tasks": train_tasks,
        "calibration_tasks": calibration_tasks,
        "sha256": curriculum_digest,
    }


def _presentation_order(
    task_count: int, schedule: str, seed: int
) -> list[int]:
    """Deterministic presentation order; every arm sees the same multiset."""
    if schedule == "massed":
        return [task for task in range(task_count) for _ in range(_CORPUS_PASSES)]
    if schedule == "spaced":
        return [
            task for _ in range(_CORPUS_PASSES) for task in range(task_count)
        ]
    if schedule == "interleaved":
        rng = np.random.default_rng([seed, 0x1A77E5])
        order: list[int] = []
        for _ in range(_CORPUS_PASSES):
            order.extend(int(index) for index in rng.permutation(task_count))
        return order
    _fail(f"unknown schedule {schedule!r}")


def _prepare_sequences(tasks: tuple) -> list[tuple[tuple[int, ...], tuple[int, ...]]]:
    protocol = typed_program.Layer1Protocol.for_lane("A2")
    prepared: list[tuple[tuple[int, ...], tuple[int, ...]]] = []
    for task in tasks:
        input_ids = typed_program._model_input(
            task.prompt,
            task.signature,
            framing_order=protocol.framing_order,
        )
        teacher_ids = typed_program._program_token_ids(task.teacher_tokens)
        prepared.append((input_ids, teacher_ids))
    return prepared


def _grow_circuit(
    curriculum: dict[str, object],
    *,
    n_cells: int,
    seed: int,
    readout_rule: str,
    schedule: str,
    supervision: str,
    codebook: Codebook | None = None,
    local_learning_rate_pa: float = 64.0,
    local_competitive_margin_pa: float = 64.0,
    inhibitory_fraction: float = DEFAULT_INHIBITORY_FRACTION,
) -> RecurrentCellCircuit:
    """Drive the circuit's observe/strengthen cycle over the scheduled corpus."""
    input_fanout = _INPUT_FANOUT
    if codebook is not None and codebook.mode != "explicit":
        input_fanout = codebook.k
    config = RecurrentCircuitConfig(
        reservoir_cells=n_cells,
        input_fanout=input_fanout,
        recurrent_fanout=_RECURRENT_FANOUT,
        random_seed=seed,
        readout_learning_rule=readout_rule,
        local_learning_rate_pa=local_learning_rate_pa,
        local_competitive_margin_pa=local_competitive_margin_pa,
        inhibitory_fraction=inhibitory_fraction,
    )
    circuit = RecurrentCellCircuit(token_cells=_TOKEN_CELLS, config=config)
    if codebook is not None and codebook.mode != "explicit":
        install_codebook(circuit, codebook)
    prepared = _prepare_sequences(curriculum["train_tasks"])  # type: ignore[arg-type]
    scope = _SUPERVISION_SCOPE[supervision]
    for task_index in _presentation_order(len(prepared), schedule, seed):
        input_ids, teacher_ids = prepared[task_index]
        training_ids = (*input_ids, *teacher_ids)
        circuit.reset_sequence()
        for index, observed_token_id in enumerate(training_ids[:-1]):
            circuit.observe(observed_token_id)
            if scope == _ALL_TRANSITION or index + 1 >= len(input_ids):
                circuit.strengthen(training_ids[index + 1])
    circuit.freeze_learning()
    return circuit


def _complete_program(
    circuit: RecurrentCellCircuit,
    input_ids: tuple[int, ...],
    signature: typed_program.TypedSignature,
    teacher_tokens: tuple[str, ...] | None,
) -> tuple[tuple[str, ...], bool, list[float]]:
    """One typed-hole completion; returns (tokens, replay_ok, margins_pa)."""
    token_to_id = typed_program._TOKEN_TO_ID
    circuit.reset_sequence()
    for token_id in input_ids:
        circuit.observe(token_id)
    state = typed_program._TypedHoleState(signature)
    tokens: list[str] = []
    margins: list[float] = []
    while not state.complete and len(tokens) < typed_program._MAX_PROGRAM_TOKENS:
        allowed_specs = state.allowed()
        if not allowed_specs:
            raise typed_program.ProgramFormatError("typed hole has no inhabiting primitive")
        allowed_cell_ids = tuple(token_to_id[spec.token] for spec in allowed_specs)
        if teacher_tokens is not None and len(tokens) < len(teacher_tokens):
            expected_cell = token_to_id.get(teacher_tokens[len(tokens)])
            if expected_cell is not None and expected_cell in allowed_cell_ids:
                currents = circuit.output_current_pa()
                competitors = [
                    float(currents[cell_id])
                    for cell_id in allowed_cell_ids
                    if cell_id != expected_cell
                ]
                if competitors:
                    margins.append(float(currents[expected_cell]) - max(competitors))
        race = circuit.race(allowed_token_ids=allowed_cell_ids)
        accepted = typed_program._ID_TO_SPEC[race.winner]
        state.consume(accepted)
        tokens.append(accepted.token)
        circuit.observe(race.winner)
    replay_ok = bool(
        state.complete
        and teacher_tokens is not None
        and tuple(tokens) == tuple(teacher_tokens)
    )
    return tuple(tokens), replay_ok, margins


def _case_results(task, tokens: tuple[str, ...]) -> tuple[int, int]:
    """Semantic case pass/total; mirrors the sealed runner's evaluation."""
    total = len(task.cases)
    try:
        source = typed_program.compile(
            typed_program.Program(tuple(tokens), task.signature)
        ).source
        namespace: dict[str, object] = {}
        exec(source, {"__builtins__": {}}, namespace)  # noqa: S102 - structural AST only
        function = namespace[task.signature.entry_point]
    except Exception:
        return 0, total
    passed = 0
    for case in task.cases:
        try:
            if function(*case.arguments) == case.expected:
                passed += 1
        except Exception:
            continue
    return passed, total


def _evaluate_cohort(
    circuit: RecurrentCellCircuit,
    tasks: tuple,
    *,
    collect_margins: bool,
) -> dict[str, object]:
    replayed = 0
    cases_total = 0
    cases_passed = 0
    margins: list[float] = []
    for task in tasks:
        input_ids = typed_program._model_input(
            task.prompt,
            task.signature,
            framing_order=typed_program.Layer1Protocol.for_lane("A2").framing_order,
        )
        try:
            tokens, replay_ok, task_margins = _complete_program(
                circuit,
                input_ids,
                task.signature,
                task.teacher_tokens if collect_margins else None,
            )
        except (typed_program.ProgramFormatError, RuntimeError):
            cases_total += len(task.cases)
            continue
        replayed += int(replay_ok)
        if collect_margins:
            margins.extend(task_margins)
        passed, total = _case_results(task, tokens)
        cases_passed += passed
        cases_total += total
    if any(not np.isfinite(value) for value in margins):
        raise RuntimeError("non-finite competitive margin observed")
    return {
        "replayed": replayed,
        "cases_total": cases_total,
        "cases_passed": cases_passed,
        "margins": margins,
    }


def _projected_peak_bytes(n_cells: int, readout_rule: str) -> int:
    reservoir = 16 * n_cells * 8
    if readout_rule == "ridge":
        normal = (n_cells + 1) * (n_cells + 1) * 8
        moments = _TOKEN_CELLS * (n_cells + 1) * 8
        synapses = _TOKEN_CELLS * n_cells * 8
        batch = 128 * (n_cells + 1) * 8
        return reservoir + normal + moments + synapses + batch
    if readout_rule == "three_factor":
        return reservoir + _TOKEN_CELLS * n_cells * 8
    candidate_count = min(n_cells, 4 * 64)
    return reservoir + _TOKEN_CELLS * (candidate_count * 16 + 64 * 16 + 16)


